package domain

import "fmt"

// Деньги в системе — всегда целое число копеек (int64). Плавающая точка не
// используется нигде: ни в контракте, ни в БД, ни в расчётах.

// Верхние границы существуют не ради красоты, а чтобы произведение цены на
// количество заведомо не переполнило int64. Без них заведение могло бы
// синхронизировать цену в 9·10¹⁸, и заказ из двух позиций дал бы отрицательную
// сумму: CHECK в БД её поймает, но клиент получит невнятную ошибку целостности
// вместо понятного отказа.
//
// При этих границах максимум произведения — 10⁸ × 10³ = 10¹¹, а сумма по сотне
// позиций — 10¹³, что на шесть порядков ниже потолка int64.
const (
	// MaxPriceKopecks — миллион рублей за позицию.
	MaxPriceKopecks int64 = 100_000_000
	// MaxItemQty — предельное количество одной позиции в заказе.
	MaxItemQty int32 = 1_000
)

// LineTotal считает стоимость позиции. Отдельная функция, чтобы правило
// «цена × количество» жило в одном месте и совпадало с CHECK-ограничением
// order_items_line_total_matches в БД.
//
// Переполнение здесь невозможно: оба сомножителя ограничены проверками
// OrderDraft.Validate и validateSyncProducts.
func LineTotal(unitPriceKopecks int64, qty int32) int64 {
	return unitPriceKopecks * int64(qty)
}

// FormatKopecks приводит копейки к человекочитаемому виду для текстов ошибок.
func FormatKopecks(kopecks int64) string {
	sign := ""
	if kopecks < 0 {
		sign = "-"
		kopecks = -kopecks
	}
	return fmt.Sprintf("%s%d,%02d ₽", sign, kopecks/100, kopecks%100)
}
