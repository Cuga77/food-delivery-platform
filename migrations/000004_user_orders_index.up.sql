-- ---------------------------------------------------------------------------
-- Индекс под историю заказов пользователя.
--
-- Прежний idx_orders_user_created (user_external_id, created_at DESC) не
-- обслуживал ни один запрос: выборки по пользователю не существовало вовсе.
-- Он платился на каждой вставке заказа и не давал ничего — ровно та же
-- ситуация, что с idx_orders_restaurant_status в миграции 000003.
--
-- Теперь такая выборка появляется: GET /api/v1/orders отдаёт историю заказов
-- пользователя постранично. Порядок в индексе совпадает с ORDER BY, а id в
-- конце делает ключ полным: created_at может совпадать у двух заказов,
-- оформленных в одну секунду, и без второго столбца курсорная пагинация
-- пропускала бы или дублировала строки на границе страницы.
-- ---------------------------------------------------------------------------

BEGIN;

CREATE INDEX idx_orders_user_recent
    ON orders (user_external_id, created_at DESC, id DESC);

COMMENT ON INDEX idx_orders_user_recent IS
    'История заказов пользователя: порядок индекса совпадает с ORDER BY, сортировка не требуется';

DROP INDEX idx_orders_user_created;

COMMIT;
