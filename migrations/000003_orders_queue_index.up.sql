-- ---------------------------------------------------------------------------
-- Индекс под очередь заказов заведения.
--
-- Запрос GET /api/v1/partner/orders выбирает заказы одного заведения,
-- отсортированные по времени, с необязательным фильтром по статусу:
--
--   WHERE restaurant_id = $1 AND ($2::text IS NULL OR status = $2::text)
--   ORDER BY created_at DESC, id DESC LIMIT $3
--
-- Прежний idx_orders_restaurant_status (restaurant_id, status) этот запрос не
-- обслуживал: конструкция «$2 IS NULL OR status = $2» не сарджируема, и
-- планировщик не может взять status ведущим равенством. В результате при
-- 120 000 заказов заведения выборка первых 50 занимала 829 мс — полное
-- сканирование с сортировкой.
--
-- Замер (PostgreSQL 17, 120 000 заказов, EXPLAIN ANALYZE):
--
--   как было ............................... 829,3 мс  Seq Scan + top-N heapsort
--   + (restaurant_id, status, created_at)... 748,8 мс  не помогает, см. выше
--   + (restaurant_id, created_at, id) .......  0,84 мс  Index Only Scan
--
-- Порядок сортировки в индексе совпадает с ORDER BY, поэтому сортировка не
-- нужна вовсе, а LIMIT останавливает чтение после пятидесятой строки.
-- Фильтр по статусу применяется поверх индекса и остаётся быстрым (0,93 мс).
-- ---------------------------------------------------------------------------

BEGIN;

CREATE INDEX idx_orders_restaurant_recent
    ON orders (restaurant_id, created_at DESC, id DESC);

COMMENT ON INDEX idx_orders_restaurant_recent IS
    'Очередь заказов заведения: порядок индекса совпадает с ORDER BY, сортировка не требуется';

-- Прежний индекс становится мёртвым грузом: единственный запрос по паре
-- (restaurant_id, status) — та же очередь заказов, и её теперь обслуживает
-- индекс выше. Оставлять означало бы платить за поддержку индекса на каждой
-- вставке и смене статуса, не получая ничего взамен.
DROP INDEX idx_orders_restaurant_status;

COMMIT;
